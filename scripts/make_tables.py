def tab_marigold():
    a, b = j("e3_summary_moge_subset.json"), j("e3_summary_marigold_subset.json")
    if not (a and b):
        return
    key = "all_snippets_frames_with_radar_anchor"
    body = "\\begin{tabular}{lcc}\n\\toprule\nProtocol (AbsRel) & MoGe-2 & Marigold \\\\\n\\midrule\n"
    for lab, k in (("LC-scene (LiDAR)", "LC-scene (LiDAR)"), ("LC-box held-out (LiDAR)", "LC-box held-out (LiDAR)"),
                   ("RC-box affine (radar)", "RC-box (radar)"), ("RC-box leave-own-out (radar)", "RC-box LOO (radar)")):
        body += f"{lab} & {f(a[key][k]['AbsRel'])} & {f(b[key][k]['AbsRel'])} \\\\\n"
