"""LaTeX tables for the paper, generated from results/*.json (never typed by hand).

Writes results/tables/*.tex; the paper \\input{}s copies of these files.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from wd2 import io  # noqa: E402

RES = io.REPO / "results"
TAB = RES / "tables"


def j(name):
    p = RES / name
    return json.load(open(p)) if p.exists() else None


def write(name, body):
    TAB.mkdir(parents=True, exist_ok=True)
    (TAB / name).write_text("% generated by scripts/make_tables.py -- do not edit by hand\n" + body)
    print("wrote", name)


def f(x, d=3):
    return "--" if x is None else f"{x:.{d}f}"


def tab_e3():
    s = j("e3_summary_anchor.json")
    if not s:
        return
    t = s["test_frames_with_radar_anchor"]
    own = s["test_animals_with_own_radar_estimate"]
    rows = [("MoGe-2 metric, no anchor", "--", "MoGe-2 metric (no anchor)"),
            ("UC: 1 LiDAR point (scale)", "L", "UC (1 LiDAR pt)"),
            ("LC-scene: all LiDAR $<$55\\,m", "L", "LC-scene (LiDAR)"),
            ("LC-box: held-out LiDAR in masks", "L", "LC-box held-out (LiDAR)"),
            ("RC-pixel: radar returns per pixel", "R", "RC-pixel (radar)"),
            ("RC-box: object-level radar (affine)", "R", "RC-box (radar)"),
            ("RC-box, scale only", "R", "RC-box scale-only (radar)"),
            ("RC-box, leave-own-anchor-out", "R", "RC-box LOO (radar)"),
            ("Radar snapped to LiDAR (earlier study)$^\\ast$", "L+R", "Radar snapped to LiDAR*")]
    body = ("\\begin{tabular}{llcccc}\n\\toprule\nAnchor & Sensor & AbsRel [95\\% CI] & medAE (m) & $\\delta{<}1.25$ & cov. \\\\\n\\midrule\n")
    for lab, sen, k in rows:
        e = t[k]
        body += (f"{lab} & {sen} & {f(e['AbsRel'])} [{f(e['AbsRel_CI95'][0])}, {f(e['AbsRel_CI95'][1])}] & "
                 f"{f(e['medAE'], 2)} & {f(e['d125'], 2)} & {f(e['coverage'], 2)} \\\\\n")
    body += "\\midrule\n\\multicolumn{6}{l}{\\emph{Same animals, where a radar range estimate exists (" + f"{own['_n_animals']:,}".replace(",", "{,}") + " animals)}} \\\\\n"
    for lab, sen, k in (("MoGe-2 metric, no anchor", "--", "MoGe-2 metric (no anchor)"),
                        ("LC-box: held-out LiDAR", "L", "LC-box held-out (LiDAR)"),
                        ("Radar range only (MoGe-gated)", "R", "Radar range only")):
        e = own[k]
        body += (f"{lab} & {sen} & {f(e['AbsRel'])} [{f(e['AbsRel_CI95'][0])}, {f(e['AbsRel_CI95'][1])}] & "
                 f"{f(e['medAE'], 2)} & {f(e['d125'], 2)} & -- \\\\\n")
    body += "\\bottomrule\n\\end{tabular}\n"
    write("tab_e3_radar_scale.tex", body)
    sel = s["radar_estimator_selection"]
    body = "\\begin{tabular}{lccc}\n\\toprule\nRadar range estimator & coverage & median rel.\\ err. & AbsRel \\\\\n\\midrule\n"
    names = {"median": "median of box returns", "nearest": "nearest range cluster", "mode": "densest range cluster",
             "prior": "MoGe-2-gated ($\\pm$35\\%)"}
